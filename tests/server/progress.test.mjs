import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../../server/index.js';
import { hashPassword } from '../../server/auth.js';

test('revision checks preserve legacy history, reject competing writers and fail closed on corrupt data', async t => {
  const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'progress-test-'));
  const app = createApp({ dataDir, getUsers: () => ({ fictional: { hash } }) });
  const hash = await hashPassword('fictional-password');
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  const login = await fetch(`${base}/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'fictional', password: 'fictional-password' }) });
  const { token } = await login.json();
  const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', 'X-Progress-Format': '1' };
  const get = () => fetch(`${base}/progress/fictional`, { headers });
  const post = body => fetch(`${base}/progress/fictional`, { method: 'POST', headers, body: JSON.stringify(body) });
  assert.equal(await (await get()).json(), null);
  assert.equal((await post({ attempts: [] })).status, 428);
  const file = path.join(dataDir, 'fictional.json');
  const legacy = { attempts: [{ id: 'old-fictional-attempt' }], hazardSessions: [{ id: 'old-fictional-session' }] };
  await fs.writeFile(file, JSON.stringify(legacy));
  assert.deepEqual(await (await get()).json(), legacy);
  const first = { ...legacy, revision: 0, attempts: [...legacy.attempts, { id: 'new-fictional-attempt' }] };
  const competing = await Promise.all([post(first), post({ ...legacy, revision: 0 })]);
  assert.deepEqual(competing.map(r => r.status).sort(), [200, 409]);
  assert.deepEqual(await competing[0].json(), { ok: true, revision: 1 });
  assert.equal((await post(first)).status, 409); // lost acknowledgement / stale tab
  const saved = await (await get()).json();
  assert.equal(saved.attempts.length, 2);
  assert.deepEqual(saved.hazardSessions, legacy.hazardSessions);
  assert.equal((await fetch(`${base}/progress/fictional`)).status, 401);
  assert.equal((await fetch(`${base}/progress/fictional`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 401);
  assert.equal((await fetch(`${base}/progress/another`, { headers })).status, 403);
  // Clients from before the compact format must reload rather than read or overwrite it.
  const oldClient = { Authorization: headers.Authorization, 'Content-Type': 'application/json' };
  assert.equal((await fetch(`${base}/progress/fictional`, { headers: oldClient })).status, 409);
  assert.equal((await fetch(`${base}/progress/fictional`, { method: 'POST', headers: oldClient, body: JSON.stringify({ revision: 0, attempts: [] }) })).status, 409);
  assert.equal((await post({ ...saved, padding: 'x'.repeat(2 * 1024 * 1024) })).status, 413);
  assert.deepEqual(await (await get()).json(), saved);
  assert.equal((await fetch(`${base}/progress/fictional`, { method: 'DELETE', headers })).status, 428);
  const reset = await post({ revision: saved.revision, attempts: [], hazardSessions: [] });
  assert.deepEqual(await reset.json(), { ok: true, revision: 2 });
  assert.equal((await post(saved)).status, 409);
  await fs.writeFile(file, '{broken');
  assert.equal((await get()).status, 500);
  assert.equal((await post(saved)).status, 500);
  assert.equal(await fs.readFile(file, 'utf8'), '{broken');
});

test('compact history appends stay small after stored history exceeds the request limit', async t => {
  const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'history-test-'));
  const hash = await hashPassword('fictional-password');
  const server = createApp({ dataDir, getUsers: () => ({ fictional: { hash } }) }).listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  const login = await fetch(`${base}/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'fictional', password: 'fictional-password' }) });
  const { token } = await login.json();
  const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', 'X-Progress-Format': '1' };
  const post = body => fetch(`${base}/progress/fictional`, { method: 'POST', headers, body: JSON.stringify(body) });
  const history = { revision: 7, historyVersion: 1, questionSnapshots: [], attempts: Array.from({ length: 40000 }, (_, i) => ({ id: `fictional-${i}`, questions: [['fictional-question', [3, 2, 1, 0], 2]], answers: [1] })) };
  assert.ok(Buffer.byteLength(JSON.stringify(history)) > 2 * 1024 * 1024);
  await fs.writeFile(path.join(dataDir, 'fictional.json'), JSON.stringify(history));
  const update = { revision: 7, historyVersion: 1, historyBaseCount: 40000, snapshotBaseCount: 0, questionSnapshots: [], attempts: [{ id: 'fictional-new', questions: [], answers: [] }] };
  assert.ok(Buffer.byteLength(JSON.stringify(update)) < 1024);
  assert.equal((await post(update)).status, 200);
  assert.equal((await post(update)).status, 409);
  const saved = await (await fetch(`${base}/progress/fictional`, { headers })).json();
  assert.equal(saved.attempts.length, 40001);
  assert.deepEqual(saved.attempts[0], history.attempts[0]);
  assert.equal(saved.historyBaseCount, undefined);
  assert.equal((await post({ ...update, revision: 8, historyBaseCount: 40001 })).status, 400);
  assert.equal((await post({ revision: 8, historyVersion: 1, questionSnapshots: [], attempts: [] })).status, 200);
  const reset = await (await fetch(`${base}/progress/fictional`, { headers })).json();
  assert.equal(reset.revision, 9);
  assert.deepEqual(reset.attempts, []);
});
